ALTER PROCEDURE [dbo].[SP_SGI_MATE_PRIMA]
(	@MV_PAR01 VARCHAR(10),
	@MV_PAR02 VARCHAR(10))
AS

------------------------------------------------------------------------------------------------------------------------------------------------------------------------
SELECT @MV_PAR01=SUBSTRING(@MV_PAR01,7,4)+SUBSTRING(@MV_PAR01,4,2)+SUBSTRING(@MV_PAR01,1,2)
SELECT @MV_PAR02=SUBSTRING(@MV_PAR02,7,4)+SUBSTRING(@MV_PAR02,4,2)+SUBSTRING(@MV_PAR02,1,2)
------------------------------------------------------------------------------------------------------------------------------------------------------------------------
SET NOCOUNT ON 
------------------------------------------------------------------------------------------------------------------------------------------------------------------------

	SELECT
		B1.B1_COD ,
		B1.B1_DESC ,
		B1.B1_GRUPO,
		BM.BM_DESC ,
		YD.YD_DESC_P,
		SUBSTRING(D1_DTDIGIT, 1, 6) AS 'ENTRADA',
		D1.D1_UM,
		D1.D1_QUANT,
		D1.D1_TOTAL,
		CASE
			WHEN D1.D1_TIPO IN ('D','B')  THEN A1.A1_NOME
			ELSE A2.A2_NOME
		END AS 'NOME'
		,D1.D1_TIPO
		,D1.D1_CF
		,X5.X5_DESCRI
	FROM SD1010 D1
	INNER JOIN SB1010 B1 ON B1.B1_COD = D1.D1_COD 
	LEFT JOIN SYD010 YD ON YD.YD_TEC = B1.B1_POSIPI 
	INNER JOIN SBM010 BM ON BM.BM_GRUPO = B1.B1_GRUPO AND BM.BM_GRUPO NOT IN ('0010')
	INNER JOIN SA2010 A2 ON A2.A2_COD = D1.D1_FORNECE AND A2.A2_LOJA = D1.D1_LOJA 
	LEFT JOIN SA1010 A1 ON A1.A1_COD = D1.D1_FORNECE AND A1.A1_LOJA = D1.D1_LOJA
	INNER JOIN SX5010 X5 ON X5.X5_TABELA = '13' AND TRIM(X5.X5_CHAVE) = TRIM(D1.D1_CF)  AND X5.X5_DESCRI LIKE '%INDUSTR%'
	WHERE D1_DTDIGIT BETWEEN @MV_PAR01  AND @MV_PAR02
	AND D1.D_E_L_E_T_ = ''
	AND D1.D1_TIPO NOT IN ('C')
------------------------------------------------------------------------------------------------------------------------------------------------------------------------
SET NOCOUNT OFF
-----------------------------------------------------------------------------------------------------------------------------------------------------------------------

