CREATE PROCEDURE [dbo].[SP_CUSTO_PJ_NF_RH]
(	@MV_PAR01		VARCHAR(10),
	@MV_PAR02		VARCHAR(10)
) AS
-------------------------------------------------------------------------------------------------------------------------------------------------------
SELECT @MV_PAR01=SUBSTRING(@MV_PAR01,7,4)+SUBSTRING(@MV_PAR01,4,2)+SUBSTRING(@MV_PAR01,1,2)
SELECT @MV_PAR02=SUBSTRING(@MV_PAR02,7,4)+SUBSTRING(@MV_PAR02,4,2)+SUBSTRING(@MV_PAR02,1,2)
-------------------------------------------------------------------------------------------------------------------------------------------------------
SET NOCOUNT ON
-------------------------------------------------------------------------------------------------------------------------------------------------------
-- VENDAS
-------------------------------------------------------------------------------------------------------------------------------------------------------

	SELECT
		E2_FILIAL AS 'FILIAL' ,
		SUBSTRING(E2_VENCREA, 1, 6) AS 'EMISSAO' ,
		ISNULL(CAST(FLOOR(E2_VALOR * 100) / 100.0 AS DECIMAL(10, 2)), 0) AS VALOR,
		E2_FORNECE AS 'FORNECEDOR',
		E2_LOJA AS 'LOJA',
		E2_NOMFOR AS 'NOME'
	FROM SE2010 E2
	INNER JOIN SA2010 A2 ON A2.A2_COD = E2_FORNECE AND A2.A2_LOJA = E2_LOJA AND A2.A2_XPJFOL = 'S'
	WHERE 
	E2.D_E_L_E_T_ = ''
	AND E2_VENCREA  BETWEEN @MV_PAR01 AND @MV_PAR02
	AND E2_TIPO IN ('NF')
	ORDER BY E2_EMISSAO  

-------------------------------------------------------------------------------------------------------------------------------------------------------
SET NOCOUNT OFF
