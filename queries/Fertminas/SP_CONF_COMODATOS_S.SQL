CREATE PROCEDURE [dbo].[SP_CONF_COMODATOS_S]
(	@MV_PAR01		VARCHAR(10),
	@MV_PAR02		VARCHAR(10)
) AS
-------------------------------------------------------------------------------------------------------------------------------------------------------
SELECT @MV_PAR01=SUBSTRING(@MV_PAR01,7,4)+SUBSTRING(@MV_PAR01,4,2)+SUBSTRING(@MV_PAR01,1,2)
SELECT @MV_PAR02=SUBSTRING(@MV_PAR02,7,4)+SUBSTRING(@MV_PAR02,4,2)+SUBSTRING(@MV_PAR02,1,2)
-------------------------------------------------------------------------------------------------------------------------------------------------------
SET NOCOUNT ON
-------------------------------------------------------------------------------------------------------------------------------------------------------
-- ENTRADA
-------------------------------------------------------------------------------------------------------------------------------------------------------

--DECLARE @MV_PAR01 CHAR(8)
--DECLARE @MV_PAR02 CHAR(8)
--SET @MV_PAR01 = '20251001'
--SET @MV_PAR02 = '20251031'
SELECT
	B1.B1_COD ,
	B1.B1_DESC ,
	D2_CF,
	TRIM(X5.X5_DESCRI) AS DESC_CF ,
	D2_TP,
	B1_GRUPO ,
	A1.A1_COD, 
	A1.A1_NOME ,
	FORMAT(CAST(D2.D2_EMISSAO AS DATE), 'dd/MM/yyyy') AS EMISSAO ,
	D2.D2_QUANT,
	D2.D2_PRCVEN,
	D2.D2_TOTAL,
	D2_DESC AS DESCONTO,
	D2.D2_ESTOQUE, 
	A1.A1_EST,
	A1.A1_MUN ,
	D2.D2_FILIAL
FROM SD2010 D2
INNER JOIN SB1010 B1 ON B1.B1_COD = D2.D2_COD AND B1.D_E_L_E_T_ = '' AND B1.B1_GRUPO NOT IN ('0012','0005','0004','0003','0002','0011')
INNER JOIN SX5010 X5 ON X5.X5_TABELA = '13' AND LEN(TRIM(X5.X5_CHAVE)) = '4' AND TRIM(X5.X5_CHAVE) = D2.D2_CF
INNER JOIN SA1010 A1 ON A1.A1_COD = D2.D2_CLIENTE AND A1.A1_LOJA = D2.D2_LOJA AND A1.D_E_L_E_T_ = ''
WHERE D2_EMISSAO BETWEEN @MV_PAR01 AND @MV_PAR02
AND D2.D_E_L_E_T_ = ''
AND D2.D2_CF NOT IN ('6557','6552','5551','5552')

-------------------------------------------------------------------------------------------------------------------------------------------------------
SET NOCOUNT OFF
