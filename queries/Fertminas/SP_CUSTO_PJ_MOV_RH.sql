-------------------------------------------------------------------------------------------------------------------------------------------------------*/
CREATE PROCEDURE [dbo].[SP_CUSTO_PJ_MOV_RH]
(	@MV_PAR01		VARCHAR(10),
	@MV_PAR02		VARCHAR(10)
) AS
-------------------------------------------------------------------------------------------------------------------------------------------------------
SELECT @MV_PAR01=SUBSTRING(@MV_PAR01,7,4)+SUBSTRING(@MV_PAR01,4,2)+SUBSTRING(@MV_PAR01,1,2)
SELECT @MV_PAR02=SUBSTRING(@MV_PAR02,7,4)+SUBSTRING(@MV_PAR02,4,2)+SUBSTRING(@MV_PAR02,1,2)
-------------------------------------------------------------------------------------------------------------------------------------------------------
SET NOCOUNT ON
-------------------------------------------------------------------------------------------------------------------------------------------------------
-- VENDAS
-------------------------------------------------------------------------------------------------------------------------------------------------------

	-- PELO MOVIMENTO 
	SELECT 
		E5_FILIAL AS 'FILIAL' ,
		SUBSTRING(E5_DATA, 1, 6) AS 'EMISSAO' ,
		ISNULL(CAST(FLOOR(E5_VALOR * 100) / 100.0 AS DECIMAL(10, 2)), 0) AS VALOR,
		E5_CLIFOR AS 'FORNECEDOR',
		E5_LOJA AS 'LOJA',
		E5_BENEF AS 'NOME', 
		E5_HISTOR AS HIST
	FROM SE5010 E5
	INNER JOIN SA2010 A2 ON A2.A2_COD = E5.E5_CLIFOR AND A2.A2_LOJA = E5.E5_LOJA  AND A2.A2_XPJFOL = 'S'
	WHERE E5.E5_DATA BETWEEN @MV_PAR01 AND @MV_PAR02
	AND E5.D_E_L_E_T_ = ''
	AND E5.E5_TIPODOC NOT IN ('CP','PA')
	ORDER BY E5.E5_CLIFOR 

-------------------------------------------------------------------------------------------------------------------------------------------------------
SET NOCOUNT OFF
-------------------------------------------------------------------------------------------------------------------------------------------------------
