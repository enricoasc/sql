CREATE PROCEDURE SP_HDS3415_RSC71
(	@MV_PAR01		VARCHAR(10),
	@MV_PAR02		VARCHAR(10)
) AS
-------------------------------------------------------------------------------------------------------------------------------------------------------
SELECT @MV_PAR01=SUBSTRING(@MV_PAR01,7,4)+SUBSTRING(@MV_PAR01,4,2)+SUBSTRING(@MV_PAR01,1,2)
SELECT @MV_PAR02=SUBSTRING(@MV_PAR02,7,4)+SUBSTRING(@MV_PAR02,4,2)+SUBSTRING(@MV_PAR02,1,2)
-------------------------------------------------------------------------------------------------------------------------------------------------------
SET NOCOUNT ON
-------------------------------------------------------------------------------------------------------------------------------------------------------
-- SCP
-------------------------------------------------------------------------------------------------------------------------------------------------------
	
	
		SELECT  C7_FILIAL,C7_NUM, A2_COD,A2_LOJA,A2_NOME,A2_NREDUZ, A2.A2_CGC  ,C7_TIPO,C7_ITEM,C7_PRODUTO,C7_DESCRI,C7_UM, C7_QUANT, C7_QUJE, (C7_QUANT - C7_QUJE) QUANT_DIFF, C7_PRECO,C7_TOTAL,C7_VLDESC,  C7_LOCAL, C7_NUMSC, 
		CONVERT(varchar(10), CONVERT(date, C7_DATPRF, 112), 103) C7_DATPRF, 
		CONVERT(varchar(10), CONVERT(date, C7.C7_EMISSAO, 112), 103) C7_EMISSAO , 
		C7_COND, C7_CC, C7_EMITIDO,C7_NUMCOT, C7_AG_USER,C7.C7_SOLICIT , C7_JUSTALT, C7_JUSTIFI
	FROM SC7200 C7
	INNER JOIN SA2200 A2 ON A2.A2_COD = C7.C7_FORNECE AND A2.A2_LOJA = C7.C7_LOJA AND A2.D_E_L_E_T_ = ''
	WHERE C7.D_E_L_E_T_ = ''
	AND C7_AG_PVVA = ''
	AND C7_UM <> 'SV'
	AND C7_EMISSAO BETWEEN @MV_PAR01 AND @MV_PAR02
	AND C7_LOCAL <> '89'
		

-------------------------------------------------------------------------------------------------------------------------------------------------------
SET NOCOUNT OFF

