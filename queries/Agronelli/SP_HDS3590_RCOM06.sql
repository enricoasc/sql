            CASE
                WHEN B.RECNO_C7 IS NULL THEN 'PENDENCIA - PEDIDO NAO LOCALIZADO'
                WHEN B.FORNECEDOR_PEDIDO <> B.FORNECEDOR_NF
                  OR B.LOJA_PEDIDO <> B.LOJA_NF THEN 'DIVERGENCIA - FORNECEDOR PC X NF'
                WHEN B.RECNO_F1 IS NULL THEN 'PENDENCIA - CABECALHO DA NF NAO LOCALIZADO'
                WHEN COALESCE(B.CONDICAO_PEDIDO, '') <> COALESCE(B.CONDICAO_NF, '')
                    THEN 'DIVERGENCIA - CONDICAO PC X NF'
                WHEN T.RECNO_E2 IS NULL THEN 'PENDENCIA - TITULO FINANCEIRO NAO LOCALIZADO'
                WHEN D.RECNO_FIG IS NULL
                 AND (T.CODIGO_BARRAS IS NOT NULL OR T.LINHA_DIGITAVEL IS NOT NULL)
                    THEN 'ATENCAO - BOLETO NO TITULO SEM DDA'
                WHEN D.RECNO_FIG IS NULL THEN 'PENDENCIA - BOLETO NAO LOCALIZADO'
                WHEN D.VENCIMENTO_DDA <>
                     COALESCE(NULLIF(T.VENCIMENTO_REAL, ''), T.VENCIMENTO_TITULO)
                    THEN 'DIVERGENCIA - VENCIMENTO DDA X TITULO'
                WHEN ABS(D.VALOR_DDA - T.VALOR_TITULO) > 0.01
                    THEN 'DIVERGENCIA - VALOR DDA X TITULO'
                ELSE 'CONFORME'
            END AS STATUS_AUDITORIA
        FROM #BASE AS B
