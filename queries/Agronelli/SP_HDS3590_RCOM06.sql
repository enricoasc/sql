/*=============================================================================
  Objeto........: dbo.SP_HDS3590_RCOM06
  Objetivo......: Auditar boletos DDA contra a condicao de pagamento do pedido
                  de compra e o titulo financeiro gerado pela nota fiscal.
  Banco.........: CCW2SA_171703_PR_PD
  Conexao.......: Agronelli_tst_local
  Granularidade.: Um item de NF/pedido por parcela financeira e boleto DDA.
  Validado em...: 2026-09-22, somente leitura, via MCP dbcode.

  Objetos validados:
    SC7060/SC7080/SC7200/SC7230 - itens dos pedidos de compra
    SD1060/SD1080/SD1200/SD1230 - itens das notas fiscais de entrada
    SF1060/SF1080/SF1200/SF1230 - cabecalhos das notas fiscais de entrada
    SE2060/SE2080/SE2200/SE2230 - titulos do contas a pagar
    FIG060/FIG080/FIG200/FIG230 - conciliacao DDA
    SA2060/SA2080/SA2200/SA2230 - fornecedores
    SE4060/SE4080/SE4200/SE4230 - condicoes de pagamento

  Criterios de auditoria:
    1. A condicao da NF deve ser igual a condicao do item do pedido.
    2. O vencimento do DDA deve ser igual ao vencimento real do titulo SE2;
       quando E2_VENCREA estiver vazio, usa-se o vencimento nominal.
    3. O valor do DDA deve ser igual ao valor do titulo, com tolerancia de R$ 0,01.

  Observacoes:
    - FIG_DATA e a data de processamento do arquivo DDA, nao a data de emissao
      juridica do boleto. E2_EMISSAO e a emissao do titulo financeiro.
    - FIG_TITULO e o documento de cobranca DDA. E2_NUMBOR e numero de bordero
      e, por isso, nao e apresentado como numero do boleto.
    - Condicoes especiais da SE4 nao sao recalculadas nesta procedure. A
      consistencia e verificada pela cadeia PC -> NF -> titulo SE2 -> DDA.
    - O periodo e limitado a menos de tres meses e os filtros de data sao
      aplicados nas tabelas fisicas antes dos JOINs de maior volume.
    - Este arquivo contem somente codigo-fonte versionado. A procedure nao foi
      criada ou alterada no banco.
=============================================================================*/
